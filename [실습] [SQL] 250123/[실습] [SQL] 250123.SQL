SELECT *
  FROM (
        SELECT ACCOUNT_ID, MAX(AMOUNT) MA, DENSE_RANK() OVER(ORDER BY MAX(AMOUNT) DESC) DR
          FROM TRANSACTIONS
         GROUP BY ACCOUNT_ID
       )
 WHERE DR <=5;
 
 
-- 5번
SELECT DEPARTMENT_ID, MAX(SALARY) - MIN(SALARY) AS SALARY_GAP
  FROM EMPLOYEES
 GROUP BY DEPARTMENT_ID
 ORDER BY DEPARTMENT_ID;
 
 
-- 6번
SELECT EMPLOYEE_ID, 
       NAME, 
       SALARY, 
       ROUND(AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) AVG_SALARY,  
       ROUND(SALARY - AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) AS DIFF
  FROM EMPLOYEES;
  

