-- 1번
SELECT *
  FROM (
        SELECT DISTINCT (SELECT NAME FROM BRANCHES B WHERE B.BRANCH_ID = L.BRANCH_ID) BRANCH_NAME, 
                        SUM(AMOUNT) OVER(PARTITION BY BRANCH_ID) TOTAL_AMOUNT, 
                        ROUND(AVG(AMOUNT) OVER(), 2) AVG_AMOUNT
          FROM LOANS L
         WHERE STATUS = 'APPROVED'
         )
 WHERE TOTAL_AMOUNT < AVG_AMOUNT;
 
 
-- 2번
SELECT E1.EMPLOYEE_ID, 
       E1.NAME, 
       NVL(E2.NAME, 'NO MANAGER') MANAGER_NAME, 
       NVL((SELECT DEPARTMENT_NAME FROM DEPARTMENTS D WHERE E2.DEPARTMENT_ID = D.DEPARTMENT_ID), 'NO DEPARTMENT') DEPT_NAME
  FROM EMPLOYEES E1
  LEFT 
  JOIN EMPLOYEES E2
    ON E1.MANAGER_ID = E2.EMPLOYEE_ID;
    

-- 3번
SELECT EMPLOYEE_ID, NAME, SALARY, ROUND(SALARY/SUM(SALARY) OVER()*100, 2) RATE
  FROM EMPLOYEES
 WHERE SALARY IS NOT NULL
 ORDER BY RATE DESC;
 
