-- 8번
SELECT *
  FROM (
         SELECT *
           FROM EMPLOYEES
          ORDER BY SALARY DESC NULLS LAST, NAME
        )
 WHERE ROWNUM <= 10;

-- 9번
SELECT NVL(TO_CHAR(HIRE_DATE, 'YYYY'), 'ALL YEARS') AS YEARLY, SUM(SALARY) AS SALARY_SUM
  FROM EMPLOYEES
 GROUP BY ROLLUP(TO_CHAR(HIRE_DATE, 'YYYY'))
 ORDER BY YEARLY;
 
-- 10번
SELECT (SELECT DEPARTMENT_NAME FROM DEPARTMENTS D WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID) DEPT_NAME, JOB_ID, SUM(SALARY)
  FROM EMPLOYEES E
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY GROUPING SETS(DEPARTMENT_ID, JOB_ID, ())
ORDER BY DEPARTMENT_ID, JOB_ID;

-- 11번
SELECT DEPARTMENT_ID, 
       NAME, 
       SALARY, 
       SUM(SALARY) OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY RANGE BETWEEN 100 PRECEDING AND 100 FOLLOWING) AS SAL
  FROM EMPLOYEES;

-- 12번
SELECT EMPLOYEE_ID, SALARY, 
        CASE WHEN SALARY >= AVG_1 THEN '직무 평균 이상'
        ELSE '직무 평균 이하'
        END AS JOB_AVG,
        CASE WHEN SALARY >= AVG_2 THEN '전체 평균 이상'
        ELSE '전체 평균 이하'
        END AS TOTAL_AVG
  FROM (
        SELECT E.*, AVG(SALARY) OVER(PARTITION BY JOB_ID) AVG_1, AVG(SALARY) OVER() AVG_2
        FROM EMPLOYEES E
        );

