SELECT DEPARTMENT_ID, SUM(SALARY) AS DEPT_SAL
  FROM EMPLOYEES
 WHERE DEPARTMENT_ID IS NOT NULL
 GROUP BY ROLLUP(DEPARTMENT_ID);

-- 12-2
SELECT TO_CHAR(HIRE_DATE, 'YYYY-MM-DD') AS HIRE_DATE, COUNT(EMPLOYEE_ID)
  FROM EMPLOYEES
 GROUP BY ROLLUP(TO_CHAR(HIRE_DATE, 'YYYY-MM-DD'))
HAVING COUNT(EMPLOYEE_ID) >= 2;


-- 12-3
SELECT NVL(BRANCH_NAME, 'All Branch') AS BRANCH_NAME, LOAN_AMOUNTS
FROM (
    SELECT (SELECT NAME FROM BRANCHES B WHERE B.BRANCH_ID = L.BRANCH_ID) BRANCH_NAME, SUM(AMOUNT) AS LOAN_AMOUNTS
      FROM LOANS L
     GROUP BY ROLLUP(BRANCH_ID)
     ORDER BY BRANCH_NAME
     );