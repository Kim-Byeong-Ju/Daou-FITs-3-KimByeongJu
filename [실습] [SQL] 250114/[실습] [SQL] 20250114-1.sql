CREATE TABLE FINANCIAL_INSTITUTION (
    FINANCE_ID NUMBER PRIMARY KEY,
    FINANCE_NAME VARCHAR2(50) NOT NULL
);


CREATE TABLE LOAN_PRODUCT (
    PRODUCT_ID NUMBER PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    FINANCE_ID NUMBER NOT NULL,
    CONSTRAINT FK_FINANCE_ID FOREIGN KEY (FINANCE_ID) REFERENCES FINANCIAL_INSTITUTION(FINANCE_ID),
    PREFERENTIAL CHAR(1),
    AVERAGE_PROFIT FLOAT,
    MAX_LIMIT NUMBER,
    RELEASE_DATE DATE
);


CREATE TABLE REVIEW (
    REVIEW_ID NUMBER PRIMARY KEY,
    PRODUCT_ID NUMBER NOT NULL,
    CONSTRAINT FK_PRODUCT_ID FOREIGN KEY (PRODUCT_ID) REFERENCES LOAN_PRODUCT(PRODUCT_ID),
    TITLE VARCHAR2(50) NOT NULL, 
    CONTENT LONG, 
    CREATED_AT DATE,
    VIEW_COUNT NUMBER,
    COMMENT_COUNT NUMBER
);

CREATE TABLE CUSTOMER (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(50),
    EMAIL VARCHAR2(100),
    GENDER VARCHAR2(50),
    AMOUNT NUMBER,
    GRADE VARCHAR2(50),
    JOIN_DATE DATE
);

ALTER TABLE REVIEW ADD CUSTOMRE_ID NUMBER ;
