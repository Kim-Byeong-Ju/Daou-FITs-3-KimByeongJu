CREATE TABLE REPLY (

    REPLY_ID NUMBER PRIMARY KEY,
    REVIEW_ID NUMBER,
    CONSTRAINT FK_REVIEW_ID FOREIGN KEY (REVIEW_ID) REFERENCES REVIEW (REVIEW_ID),
    CUSTOMER_ID NUMBER,
    CONSTRAINT FK_CUSTOMER_ID_2 FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
    CONTENT VARCHAR2(100),
    CREATED_AT DATE
    );
    

CREATE TABLE ROOM (
    ROOM_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(50) ,
    CREATED_AT DATE
    );
    
CREATE TABLE CHATTING_MEMBER (
     CHAT_MEMBER_ID NUMBER PRIMARY KEY,
     ROOM_ID NUMBER NOT NULL,
     CONSTRAINT FK_ROOM_ID FOREIGN KEY (ROOM_ID) REFERENCES ROOM (ROOM_ID),
     CUSTORMER_NAME NUMBER,
     CREATED_AT DATE
);

CREATE TABLE CHAT (
    CHAT_ID NUMBER PRIMARY KEY,
    CREATED_AT DATE,
    UPDATED_AT DATE,
    CUSTOMER_ID NUMBER,
    ROOM_ID NUMBER,
    CONSTRAINT FK_CHAT_ROOM_ID FOREIGN KEY(ROOM_ID) REFERENCES ROOM (ROOM_ID)
    );


