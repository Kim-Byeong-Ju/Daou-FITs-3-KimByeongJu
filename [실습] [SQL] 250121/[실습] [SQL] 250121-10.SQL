-- 10-1번
SELECT ACCOUNT_ID, AMOUNT, SUM(AMOUNT) OVER(PARTITION BY ACCOUNT_ID ORDER BY TRANSACTION_DATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACC_AMOUNT
FROM TRANSACTIONS;

-- 10-2번
SELECT ACCOUNT_ID, (AMOUNT / MAX(AMOUNT) OVER(PARTITION BY ACCOUNT_ID)) AS MAX_RATE
FROM TRANSACTIONS;

-- 10-3번
SELECT BRANCH_ID, AMOUNT, SUM(AMOUNT) OVER(PARTITION BY BRANCH_ID ORDER BY LOAN_DATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACC_AMOUNT
FROM LOANS;

-- 10-4번
SELECT CUSTOMER_ID,BALANCE, ROUND(AVG(BALANCE) OVER(PARTITION BY CUSTOMER_ID), 2) AS AVG_BALANCE
FROM ACCOUNTS;
