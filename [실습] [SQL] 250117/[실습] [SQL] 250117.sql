SELECT E.NAME,
       D.DEPARTMENT_NAME
  FROM EMPLOYEES E
  LEFT 
  JOIN DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
 WHERE E.SALARY IS NULL;


-- 9번
SELECT *
  FROM 
      (
        SELECT C.CUSTOMER_ID, MAX(L.AMOUNT) MAX_LOAN
          FROM CUSTOMERS C, LOANS L
         WHERE C.CUSTOMER_ID = L.CUSTOMER_ID
         GROUP 
            BY C.CUSTOMER_ID
         ORDER
            BY MAX_LOAN DESC
      )
 WHERE ROWNUM <= 15;
 
-- 10번
SELECT DEPARTMENT_NAME, 
       COUNT(EMPLOYEE_ID) EMPLOYEES_COUNT
  FROM DEPARTMENTS D, EMPLOYEES E
 WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID AND
       E.SALARY BETWEEN 7000 AND 15000
 GROUP
    BY DEPARTMENT_NAME
HAVING COUNT(EMPLOYEE_ID) >= 5
 ORDER
    BY EMPLOYEES_COUNT DESC;