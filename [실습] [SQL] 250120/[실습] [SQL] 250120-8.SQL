SELECT NAME
FROM CUSTOMERS
WHERE CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM LOANS WHERE BRANCH_ID IN (SELECT BRANCH_ID FROM BRANCHES WHERE LOCATION = 'Location 1'));

-- 8-2
SELECT *
FROM TRANSACTIONS
WHERE ACCOUNT_ID IN (SELECT ACCOUNT_ID FROM ACCOUNTS WHERE CUSTOMER_ID = 100);


-- 8-3
SELECT CUSTOMER_ID, BALANCE
FROM ACCOUNTS A1
WHERE BALANCE = (SELECT MAX(BALANCE) FROM ACCOUNTS A2 WHERE A1.CUSTOMER_ID = A2.CUSTOMER_ID)
ORDER BY CUSTOMER_ID;
